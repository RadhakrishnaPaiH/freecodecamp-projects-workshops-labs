# Report Card Printer - Variable Types Demo

# Student name stored as a string
name = 'Alice'
print(name, type(name))

# Boolean value to check student status
is_student = True
print(is_student, type(is_student))

# Integer value representing age
age = 20
print(age, type(age))

# Float value representing score/marks
score = 80.5

# Check whether score is a float data type
print(isinstance(score, float))

# Print score and its data type
print(score, type(score))